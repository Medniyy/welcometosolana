/* First-visit terms gate.

   Shown once, remembered, and re-shown only when TERMS_VERSION changes — so a
   returning visitor is never asked twice for the same thing, and a material
   change to the Terms genuinely gets acknowledged again.

   Two deliberate constraints:

   - It renders itself rather than living in every page's markup, because it
     has to appear on all of them and duplicated markup drifts.
   - It fails open. If localStorage throws (private browsing) or anything here
     errors, the site stays usable. A legal notice that can lock someone out
     of a page is worse than one they saw a second time.                     */

(function () {
  "use strict";

  var TERMS_VERSION = 1;
  var KEY = "wts.terms.accepted.v" + TERMS_VERSION;

  function stored() {
    try { return window.localStorage.getItem(KEY); } catch (e) { return null; }
  }
  function remember() {
    try { window.localStorage.setItem(KEY, new Date().toISOString()); } catch (e) { /* private mode */ }
  }
  function track(n, d) {
    try { if (window._track) window._track(n, d || {}); } catch (e) { /* noop */ }
  }

  /* Already accepted, or we are on the Terms page itself — covering the Terms
     with a modal that links to the Terms is a small absurdity. */
  if (stored()) return;
  if (/\/terms(\.html)?$/.test(window.location.pathname)) return;

  function build() {
    var d = document.createElement("dialog");
    d.className = "consent";
    d.id = "consent";
    d.setAttribute("aria-labelledby", "consent-title");
    d.innerHTML =
      '<div class="consent-inner">' +
        '<p class="eyebrow">Before you start</p>' +
        '<h2 id="consent-title">Please read this.</h2>' +
        '<p class="consent-lede">This site is an interface, not a financial ' +
          'service. Moving assets carries risk, and the parts that actually ' +
          'move them are run by other people.</p>' +
        '<ul class="consent-points">' +
          '<li><strong>We never hold your funds or keys.</strong> Deposit ' +
            'addresses are generated by the routing network, not by us. We ' +
            'cannot access, reverse, or recover a transfer.</li>' +
          '<li><strong>Independent networks do the work.</strong> Transfers ' +
            'run over <a href="https://near-intents.org" target="_blank" rel="noopener">NEAR Intents</a>, ' +
            '<a href="https://skip.build/" target="_blank" rel="noopener">Skip:Go</a>, ' +
            'Circle CCTP and your own wallet. We do not control them and are ' +
            'not responsible if they are delayed, fail, or lose funds.</li>' +
          '<li><strong>Transactions are final.</strong> Sent on the wrong ' +
            'network or to the wrong address, crypto is generally gone for ' +
            'good. Check the address, network, token and amount every time.</li>' +
          '<li><strong>Quotes are estimates.</strong> They come from ' +
            'third-party solvers and move with the market. A 0.5% service fee ' +
            'is included in what you see.</li>' +
          '<li><strong>Nothing here is advice.</strong> No endorsement of any ' +
            'listed project or provider. Only move what you can afford to lose.</li>' +
        '</ul>' +
        '<div class="consent-actions">' +
          '<button class="button button--primary" type="button" id="consent-ok">' +
            '<span>I understand and agree</span>' +
            '<span class="button-icon" aria-hidden="true">→</span>' +
          '</button>' +
          '<a class="consent-read" href="terms.html">Read the full Terms and Risk Disclosure</a>' +
        '</div>' +
        '<p class="consent-foot">By continuing you agree to the ' +
          '<a href="terms.html">Terms of Use</a>. Community-made and open source.</p>' +
      '</div>';
    return d;
  }

  function open() {
    var d = build();
    document.body.appendChild(d);

    if (typeof d.showModal === "function") {
      d.showModal();
    } else {
      /* No <dialog> support: fall back to a plain fixed overlay rather than
         leaving the notice invisible. */
      d.setAttribute("open", "");
      d.classList.add("consent--fallback");
    }

    /* The whole point is an explicit acknowledgement, so Escape must not
       count as one. The button is the only way out. */
    d.addEventListener("cancel", function (e) { e.preventDefault(); });

    document.getElementById("consent-ok").addEventListener("click", function () {
      remember();
      track("terms_accepted", { version: TERMS_VERSION });
      if (typeof d.close === "function" && d.open) d.close();
      d.remove();
    });

    track("terms_shown", { version: TERMS_VERSION });
  }

  try {
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", open);
    } else {
      open();
    }
  } catch (e) { /* never block the site on this */ }
})();
